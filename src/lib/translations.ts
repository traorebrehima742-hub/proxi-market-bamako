export type TranslationKey = keyof typeof TRANSLATIONS['fr'];

export function getTranslation(lang: AppLanguage, key: TranslationKey, params?: Record<string, string | number>): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.fr;
  let text: string = dictionary[key] || TRANSLATIONS.fr[key] || key;

  if (params) {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
    });
  }

  return text;
}
